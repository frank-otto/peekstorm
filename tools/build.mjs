// Build: bundles src/ (three.js + addons) into ONE classic script (js/game.bundle.js) so index.html works via file://,
// and embeds the CC0 sound samples (sounds/*.mp3) as base64 into js/sounds-src.js.
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import { build } from 'esbuild';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
await build({ entryPoints: [resolve(root, 'src/entry.js')], bundle: true, format: 'iife', minify: !process.env.DEV, target: ['es2020', 'safari15'], outfile: resolve(root, 'js/game.bundle.js'), legalComments: 'eof' });
const obj = {};
for (const f of readdirSync(resolve(root, 'sounds')).filter(f => f.endsWith('.mp3')).sort()) obj[f.replace(/\.mp3$/, '')] = readFileSync(resolve(root, 'sounds', f)).toString('base64');
writeFileSync(resolve(root, 'js/sounds-src.js'), '/* generated by tools/build.mjs — CC0 samples, see LICENSES/SOUNDS.md */\nwindow.PS_SOUNDS = ' + JSON.stringify(obj) + ';\n');
console.log('built', Object.keys(obj).length, 'sounds');
